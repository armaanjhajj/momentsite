#!/usr/bin/env node
//
// Stamps embedding.json and zones.json with a content hash, and emits the
// stripped atlas the map draws.
//
//   node scripts/stamp-map-version.mjs
//
// WHY A VERSION EXISTS AT ALL
//
// A post stores the code it was written with. The map underneath it moves:
// growing the curated set from 152 to 157 re-fitted all 87 descriptor
// directions and changed where every text query lands, which silently
// mis-files every post written before that rebuild. The version is how a row
// knows whether its coordinates were computed under the map that is currently
// shipping.
//
// THE HASH EXCLUDES ITSELF
//
// Hashing the whole file would be self-referential: writing the hash in
// changes the hash. So each file is hashed over the fields that actually
// determine placement, with any existing `version` key ignored.
//
//   embedding.json   components + embeddings  (the descriptor directions and
//                                              the curated positions)
//   zones.json       tree + pcaBasis + pcaMean + the three name tables
//
// Deterministic: same inputs, same version, no timestamps.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const DATA = join(ROOT, "src", "data", "scent");
const PUBLIC = join(ROOT, "public", "scent");

const XY_ROUND = 3;

/** Stable stringify, so key order cannot change the hash. */
function canonical(value) {
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.keys(value)
      .sort()
      .map((k) => `${JSON.stringify(k)}:${canonical(value[k])}`)
      .join(",")}}`;
  }
  return JSON.stringify(value);
}

const short = (obj, fields) =>
  createHash("sha256")
    .update(canonical(Object.fromEntries(fields.map((f) => [f, obj[f]]))))
    .digest("hex")
    .slice(0, 12);

// ── stamp ───────────────────────────────────────────────────────────

const embPath = join(DATA, "embedding.json");
const zonePath = join(DATA, "zones.json");

const emb = JSON.parse(readFileSync(embPath, "utf8"));
const zones = JSON.parse(readFileSync(zonePath, "utf8"));

const embVersion = short(emb, ["components", "embeddings"]);
const zoneVersion = short(zones, [
  "tree",
  "pcaBasis",
  "pcaMean",
  "macroNames",
  "subNames",
  "cellNames",
]);

emb.version = embVersion;
zones.version = zoneVersion;

writeFileSync(embPath, JSON.stringify(emb, null, 1) + "\n");
writeFileSync(zonePath, JSON.stringify(zones) + "\n");

const mapVersion = `${embVersion}.${zoneVersion}`;

// The TS side reads this rather than importing two big JSON files just to get
// two strings.
writeFileSync(
  join(DATA, "map-version.ts"),
  [
    "// GENERATED by scripts/stamp-map-version.mjs. Do not edit.",
    "//",
    "// Content hash of the descriptor directions and the zone tree. Every post",
    "// is stamped with this, so a row can be told apart from one written under",
    "// an older map. Run npm run scent:rezone after this changes.",
    "",
    `export const EMBEDDING_VERSION = ${JSON.stringify(embVersion)};`,
    `export const ZONES_VERSION = ${JSON.stringify(zoneVersion)};`,
    `export const MAP_VERSION = ${JSON.stringify(mapVersion)};`,
    "",
  ].join("\n")
);

// ── the stripped atlas the map draws ────────────────────────────────
//
// public/, not src/data/, because the map fetches it after first paint. Inlined
// it would put a six figure byte count into the /scent bundle for points that
// are explicitly non-interactive.

const atlas = JSON.parse(readFileSync(join(PUBLIC, "atlas.json"), "utf8"));
const r = (x) => Number(x.toFixed(XY_ROUND));

const xyOut = {
  note:
    "id and 2D position for every GS-LF molecule, for the background layer of " +
    "the map. Built by scripts/stamp-map-version.mjs.",
  version: embVersion,
  n: atlas.molecules.length,
  ids: atlas.molecules.map((m) => m.id),
  xy: atlas.molecules.map((m) => [r(m.xy[0]), r(m.xy[1])]),
};

const xyPath = join(PUBLIC, "atlas-xy.json");
writeFileSync(xyPath, JSON.stringify(xyOut));

const kb = (p) => (readFileSync(p).length / 1024).toFixed(0);

console.log(`  embedding.json  version ${embVersion}`);
console.log(`  zones.json      version ${zoneVersion}`);
console.log(`  map version     ${mapVersion}`);
console.log(`  atlas-xy.json   ${xyOut.n} points, ${kb(xyPath)} KB (fetched, not bundled)`);
